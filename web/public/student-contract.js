const ONES = ["", "бир", "икки", "уч", "тўрт", "беш", "олти", "етти", "саккиз", "тўққиз"];
const TENS = ["", "ўн", "йигирма", "ўттиз", "қирқ", "эллик", "олтмиш", "етмиш", "саксон", "тўқсон"];
const SCALES = ["", "минг", "миллион", "миллиард"];

function triple(n) {
  const words = [];
  const h = Math.floor(n / 100);
  const t = Math.floor((n % 100) / 10);
  const o = n % 10;
  if (h) words.push(`${ONES[h]} юз`);
  if (t) words.push(TENS[t]);
  if (o) words.push(ONES[o]);
  return words.join(" ");
}

// 2200000 → "икки миллион икки юз минг"
export function numberToUzWords(value) {
  let n = Math.floor(Number(String(value ?? "").replace(/\D/g, "")) || 0);
  if (!n) return "нол";
  const parts = [];
  let scale = 0;
  while (n > 0 && scale < SCALES.length) {
    const chunk = n % 1000;
    if (chunk) parts.unshift([triple(chunk), SCALES[scale]].filter(Boolean).join(" "));
    n = Math.floor(n / 1000);
    scale += 1;
  }
  return parts.join(" ");
}

export function formatPrice(value) {
  const digits = String(value ?? "").replace(/\D/g, "");
  return digits ? Number(digits).toLocaleString("ru-RU").replace(/ /g, " ") : "";
}

