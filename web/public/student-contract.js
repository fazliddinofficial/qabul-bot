export function cyrDate(iso) {
  const m = String(iso || "").match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!m) return "«____» ______________ 20____ й.";
  return `«${Number(m[3])}» ${MONTHS_CYR[Number(m[2]) - 1]} ${m[1]} й.`;
}

